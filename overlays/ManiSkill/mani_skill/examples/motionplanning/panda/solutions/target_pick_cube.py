"""MPLib expert for the episode's designated TargetPickCube object."""

import numpy as np
import sapien

from mani_skill.examples.motionplanning.base_motionplanner.utils import (
    compute_grasp_info_by_obb,
    get_actor_obb,
)
from mani_skill.examples.motionplanning.panda.motionplanner import (
    PandaArmMotionPlanningSolver,
)


def _box_surface_points(cube, half_size):
    """Deterministic dense surface samples for MPLib's collision point cloud."""
    grid = np.linspace(-half_size, half_size, 11)
    uv = np.stack(np.meshgrid(grid, grid), axis=-1).reshape(-1, 2)
    faces = []
    for axis in range(3):
        for sign in [-1, 1]:
            points = np.empty((len(uv), 3))
            points[:, axis] = sign * half_size
            points[:, [i for i in range(3) if i != axis]] = uv
            faces.append(points)
    points = np.concatenate(faces)
    transform = cube.pose.sp.to_transformation_matrix()
    return points @ transform[:3, :3].T + transform[:3, 3]


def solve(env, seed=None, debug=False, vis=False):
    """Reset once, select target_idx, then plan and execute a target grasp.

    Returns the final Gymnasium step tuple or -1 on a failed plan/grasp.
    All arm trajectories are generated by MPLib and executed as joint targets.
    """
    env.reset(seed=seed)
    base = env.unwrapped
    if base.num_envs != 1 or base.robot_uids != "panda":
        raise ValueError("This expert supports one Panda environment per process")
    target_idx = int(base.target_idx.item())
    target = base.cubes[target_idx]
    planner = PandaArmMotionPlanningSolver(
        env,
        debug=debug,
        vis=vis,
        base_pose=base.agent.robot.pose,
        visualize_target_grasp_pose=vis,
        print_env_info=False,
        joint_vel_limits=0.7,
        joint_acc_limits=0.7,
    )
    try:
        for index, cube in enumerate(base.cubes):
            if index != target_idx:
                planner.add_collision_pts(_box_surface_points(cube, base.cube_half_size))

        approaching = np.array([0, 0, -1])
        closing = base.agent.tcp.pose.to_transformation_matrix()[0, :3, 1].cpu().numpy()
        grasp_info = compute_grasp_info_by_obb(
            get_actor_obb(target),
            approaching=approaching,
            target_closing=closing,
            depth=0.025,
        )
        grasp_pose = base.agent.build_grasp_pose(
            approaching, grasp_info["closing"], target.pose.sp.p
        )
        reach_pose = grasp_pose * sapien.Pose([0, 0, -0.10])
        for pose in [reach_pose, grasp_pose]:
            result = planner.move_to_pose_with_screw(pose)
            if isinstance(result, int):
                return -1
        result = planner.close_gripper(t=10)
        if not result[-1]["is_target_grasped"].item():
            return -1

        # Raise before lateral transport to clear the two distractor cubes.
        goal = base.goal_site.pose.sp.p.copy()
        lift = target.pose.sp.p.copy()
        lift[2] = max(0.18, float(goal[2]) + 0.05)
        above_goal = goal.copy()
        above_goal[2] = lift[2]
        for position in [lift, above_goal, goal]:
            result = planner.move_to_pose_with_screw(
                sapien.Pose(position, grasp_pose.q), refine_steps=3
            )
            if isinstance(result, int):
                return -1
        return planner.close_gripper(t=12)
    finally:
        planner.close()
